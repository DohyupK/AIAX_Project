-- 화면: 불량 유형 라벨링 (/casting/defect-labeling). 목업 없음 (빈 테이블)
BEGIN;

CREATE SCHEMA ai;
COMMENT ON SCHEMA ai IS '사람·AI가 만드는 판정·라벨·모델 정보';

-- 라벨한 샷 (불량 유형 탐지 모델의 학습 정답)
CREATE TABLE ai.defect_label (
    defect_label_idx  integer     NOT NULL UNIQUE,
    casting_id        text        PRIMARY KEY REFERENCES mes.investment_casting(casting_id),
    blowhole          boolean     NOT NULL DEFAULT false,   -- 기공
    edge_burr         boolean     NOT NULL DEFAULT false,   -- 버·플래시
    surface_rough     boolean     NOT NULL DEFAULT false,   -- 표면 결함
    labeled_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT defect_label_one_type CHECK (blowhole OR edge_burr OR surface_rough)
);
COMMENT ON TABLE ai.defect_label IS '불량 유형 라벨 (샷당 1행, 여러 유형 가능). 판정 불가는 defect_discard';

-- 폐기한 샷 (판정 불가, 학습에서 제외하되 보관)
CREATE TABLE ai.defect_discard (
    defect_discard_idx  integer     NOT NULL UNIQUE,
    casting_id          text        PRIMARY KEY REFERENCES mes.investment_casting(casting_id),
    discarded_at        timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE ai.defect_discard IS '판정 불가(UNDECIDABLE) 샷. 학습 데이터에서 제외';

-- 한 샷은 라벨·폐기 중 한 곳에만
CREATE FUNCTION ai.check_label_or_discard() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'ai'
AS $$
BEGIN
  IF TG_TABLE_NAME = 'defect_label'
     AND EXISTS (SELECT 1 FROM ai.defect_discard WHERE casting_id = NEW.casting_id) THEN
    RAISE EXCEPTION '이미 폐기된 샷입니다. 폐기에서 먼저 지우세요: %', NEW.casting_id;
  ELSIF TG_TABLE_NAME = 'defect_discard'
     AND EXISTS (SELECT 1 FROM ai.defect_label WHERE casting_id = NEW.casting_id) THEN
    RAISE EXCEPTION '이미 라벨된 샷입니다. 라벨에서 먼저 지우세요: %', NEW.casting_id;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_defect_label_only_one
    BEFORE INSERT OR UPDATE OF casting_id ON ai.defect_label
    FOR EACH ROW EXECUTE FUNCTION ai.check_label_or_discard();
CREATE TRIGGER trg_defect_discard_only_one
    BEFORE INSERT OR UPDATE OF casting_id ON ai.defect_discard
    FOR EACH ROW EXECUTE FUNCTION ai.check_label_or_discard();

