-- ===== 모델 레지스트리 (DH 요청, 2026-11-18) =====

CREATE TABLE ai.model_registry (
    model_registry_idx  integer     NOT NULL UNIQUE,
    model_name          text        NOT NULL,                     -- 예: DieCasting_XGB
    version             text        NOT NULL,                     -- 예: 3.2, v1.0
    process_code        text        NOT NULL
                        CHECK (process_code IN ('CAST-OPT', 'CAST-QC', 'SAFE-GATE')),  -- 공정 최적화 / 품질 검사 / 안전 관리
    description         text,
    accuracy_score      numeric(5,4) NOT NULL CHECK (accuracy_score  BETWEEN 0 AND 1),
    recall_score        numeric(5,4) NOT NULL CHECK (recall_score    BETWEEN 0 AND 1),
    precision_score     numeric(5,4) NOT NULL CHECK (precision_score BETWEEN 0 AND 1),
    f1_score            numeric(5,4) NOT NULL CHECK (f1_score        BETWEEN 0 AND 1),
    file_name           text,                                     -- 모델 파일 이름 (업로드는 선택)
    file_path           text,                                     -- 서버 저장 경로
    deployed            boolean     NOT NULL DEFAULT false,       -- 공정당 1개만 true
    created_at          timestamptz NOT NULL DEFAULT now(),       -- 등록일
    PRIMARY KEY (model_name, version)
);
COMMENT ON TABLE ai.model_registry IS '모델 목록. 배포하면 같은 공정의 기존 배포는 트리거가 자동으로 해제';

-- 공정당 배포 1개
CREATE UNIQUE INDEX model_registry_one_deployed
    ON ai.model_registry (process_code) WHERE deployed;

-- 새 모델을 배포하면 같은 공정의 기존 배포를 자동 해제
CREATE FUNCTION ai.on_model_deploy() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'ai'
AS $$
BEGIN
  IF NEW.deployed AND (TG_OP = 'INSERT' OR NOT OLD.deployed OR NEW.process_code IS DISTINCT FROM OLD.process_code) THEN
    UPDATE ai.model_registry SET deployed = false
     WHERE process_code = NEW.process_code AND deployed
       AND (model_name, version) IS DISTINCT FROM (NEW.model_name, NEW.version);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_model_registry_deploy
    BEFORE INSERT OR UPDATE OF deployed, process_code ON ai.model_registry
    FOR EACH ROW EXECUTE FUNCTION ai.on_model_deploy();

GRANT SELECT ON ai.model_registry TO role_lake, role_spark;

